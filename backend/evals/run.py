"""Offline evaluation of the GRIEVANCE agents.

    cd backend
    python -m evals.run                                   # hashing embedder (fast, no model download)
    python -m evals.run --embedder sentence-transformers  # multilingual transformer (needs requirements-ml.txt)

Everything runs against a throw-away SQLite database seeded with the SYNTHETIC datasets, with LLM
calls disabled, so results are deterministic and reproducible on any machine. Results are written to
evals/results/<embedder>.json and summarised in evals/results/<embedder>.md.

What is measured, and against what:

  intake       rules classifier (the deterministic fallback every request can fall back to) on
               evals/datasets/intake.jsonl; per-language accuracy; sensitive-case routing recall
               through the real policy gate.
  injection    the INJECTION_PATTERNS guard on evals/datasets/injection.jsonl.
  duplicates   the production `score_pair` + `thresholds` on every same-department pair in
               evals/datasets/duplicates.jsonl (the candidate set production compares).
  rag          the production `retrieve` over the seeded synthetic history; relevance proxy = the
               precedent has the query's gold category.
  sla          chronological rolling-origin backtest of `predictive.estimate` on the synthetic history;
               every prediction uses only cases resolved before the complaint was filed.

All evaluation inputs were written by the project author; none are real citizen complaints. The
SLA history is generated by scripts/generate_synthetic_data.py, so the backtest shows whether the
estimator recovers the generator's distribution, not real-world accuracy.
"""
