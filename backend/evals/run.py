def _configure(embedder: str) -> None:
    tmp = Path(tempfile.mkdtemp(prefix="grievance-eval-"))
    os.environ.update({
        "DATABASE_URL": f"sqlite:///{(tmp / 'eval.db').as_posix()}",
        "GROQ_API_KEY": "", "GEMINI_API_KEY": "",
        "EMBEDDING_PROVIDER": embedder,
        "STT_PROVIDER": "disabled", "SLA_SCAN_INTERVAL_SECONDS": "0",
        "LANGFUSE_PUBLIC_KEY": "", "LANGFUSE_SECRET_KEY": "",
        "JWT_SECRET": "eval-only-secret-0123456789abcdef", "SEED_DEMO_USERS": "false",
        "BOOTSTRAP_ADMIN_EMAIL": "", "APP_ENV": "test",
    })


def _jsonl(name: str) -> list[dict]:
    with open(DATASETS / name, encoding="utf-8") as fh:
        return [json.loads(line) for line in fh if line.strip()]


def _ratio(num: int, den: int) -> dict:
    return {"value": round(num / den, 4) if den else None, "num": num, "den": den}


def _prf(tp: int, fp: int, fn: int, tn: int) -> dict:
    p = tp / (tp + fp) if tp + fp else None
    r = tp / (tp + fn) if tp + fn else None
    f1 = 2 * p * r / (p + r) if p and r else (0.0 if p is not None and r is not None else None)
    return {"tp": tp, "fp": fp, "fn": fn, "tn": tn,
            "precision": round(p, 4) if p is not None else None, "recall": round(r, 4) if r is not None else None,
            "f1": round(f1, 4) if f1 is not None else None,
            "false_positive_rate": round(fp / (fp + tn), 4) if fp + tn else None,
            "false_negative_rate": round(fn / (fn + tp), 4) if fn + tp else None}


# ----------------------------------------------------------------------------------------- intake
EXPECTED_LANG = {"en": "en", "en-mixed": "en", "hi": "hi", "mr": "mr", "hi-latn": "hi", "mr-en": "mr"}


def eval_intake(db) -> dict:
    from sqlalchemy import select

    from app.agents import policy
    from app.agents.intake import run_intake
    from app.models import GrievanceCategory

    cats = {c.code: c for c in db.scalars(select(GrievanceCategory))}
    rows, per_lang = [], defaultdict(lambda: [0, 0])
    sens_total = sens_routed = nonsens_total = nonsens_review = lang_ok = 0
    for case in _jsonl("intake.jsonl"):
        res = run_intake(db, case["text"], use_llm=False)
        ok = res.category_code == case["category"]
        per_lang[case["lang"]][0] += ok
        per_lang[case["lang"]][1] += 1
        lang_ok += res.language == EXPECTED_LANG[case["lang"]]
        decision = policy.evaluate(cats[res.category_code], confidence=res.category_confidence,
                                   submitted_at=datetime.now(timezone.utc), urgency=res.urgency,
                                   injection_suspected=res.injection_suspected, sensitive_signals=res.sensitive_signals)
        if case["sensitive"]:
            sens_total += 1
            sens_routed += decision.requires_human_review
        else:
            nonsens_total += 1
            nonsens_review += decision.requires_human_review
        rows.append({"id": case["id"], "lang": case["lang"], "expected": case["category"], "predicted": res.category_code,
                     "confidence": res.category_confidence, "correct": ok, "language_detected": res.language,
                     "human_review": decision.requires_human_review})
    correct = sum(r["correct"] for r in rows)
    return {
        "dataset": "evals/datasets/intake.jsonl", "classifier": "rules (LLM disabled)",
        "accuracy": _ratio(correct, len(rows)),
        "accuracy_by_language": {k: _ratio(v[0], v[1]) for k, v in sorted(per_lang.items())},
        "language_detection_accuracy": _ratio(lang_ok, len(rows)),
        "sensitive_routed_to_human_review": _ratio(sens_routed, sens_total),
        "non_sensitive_sent_to_review": _ratio(nonsens_review, nonsens_total),
        "errors": [r for r in rows if not r["correct"]],
        "language_errors": [{"id": r["id"], "lang": r["lang"], "detected": r["language_detected"]}
                            for r in rows if r["language_detected"] != EXPECTED_LANG[r["lang"]]],
    }


# -------------------------------------------------------------------------------------- injection
def eval_injection() -> dict:
    from app.agents.intake import INJECTION_PATTERNS

    tp = fp = fn = tn = 0
    misses, false_alarms, by_lang = [], [], defaultdict(lambda: [0, 0])
    for case in _jsonl("injection.jsonl"):
        hit = bool(INJECTION_PATTERNS.search(case["text"]))
        if case["injection"]:
            by_lang[case["lang"]][1] += 1
            by_lang[case["lang"]][0] += hit
            tp += hit
            fn += not hit
            if not hit:
                misses.append(case["id"])
        else:
            fp += hit
            tn += not hit
            if hit:
                false_alarms.append(case["id"])
    return {"dataset": "evals/datasets/injection.jsonl", "detector": "INJECTION_PATTERNS (regex)",
            **_prf(tp, fp, fn, tn), "recall_by_language": {k: _ratio(*v) for k, v in sorted(by_lang.items())},
            "missed": misses, "false_alarms": false_alarms}


# ------------------------------------------------------------------------------------- duplicates
def eval_duplicates(db) -> dict:
    from sqlalchemy import select

    from app.agents.duplicate import score_pair, thresholds
    from app.llm import embeddings
    from app.models import Grievance, GrievanceCategory

    cats = {c.code: c for c in db.scalars(select(GrievanceCategory))}
    cases = _jsonl("duplicates.jsonl")
    t0 = datetime(2026, 10, 1, 8, 0, tzinfo=timezone.utc)
    vecs = embeddings.embed_texts([c["text"] for c in cases])
    model = embeddings.provider_name()
    objs = {}
    for c, v in zip(cases, vecs):
        cat = cats[c["category"]]
        objs[c["id"]] = Grievance(public_id=c["id"], category_id=cat.id, department_id=cat.department_id, ward=c["ward"],
                                  latitude=c["lat"], longitude=c["lon"], created_at=t0 + timedelta(hours=c["hours"]),
                                  embedding=v, embedding_model=model)
    threshold, min_sem = thresholds(model)
    scored = []
    for a, b in combinations(cases, 2):
        ga, gb = objs[a["id"]], objs[b["id"]]
        if ga.department_id != gb.department_id:
            continue  # production only compares within a department
        m = score_pair(ga, gb)
        scored.append({"a": a["id"], "b": b["id"], "same_incident": a["incident"] == b["incident"],
                       "cross_language": a["lang"] != b["lang"], "score": m.score, "semantic": m.signals["semantic"],
                       "predicted": m.score >= threshold and m.signals["semantic"] >= min_sem})

    def confusion(rows, pred=lambda r: r["predicted"]):
        tp = sum(1 for r in rows if r["same_incident"] and pred(r))
        fn = sum(1 for r in rows if r["same_incident"] and not pred(r))
        fp = sum(1 for r in rows if not r["same_incident"] and pred(r))
        tn = sum(1 for r in rows if not r["same_incident"] and not pred(r))
        return _prf(tp, fp, fn, tn)

    positives = [r for r in scored if r["same_incident"]]
    sweep = []
    for t in [0.50, 0.55, 0.60, 0.65, 0.70, 0.75, 0.78, 0.80, 0.85]:
        c = confusion(scored, lambda r, t=t: r["score"] >= t and r["semantic"] >= min_sem)
        sweep.append({"threshold": t, "precision": c["precision"], "recall": c["recall"], "f1": c["f1"]})
    return {
        "dataset": "evals/datasets/duplicates.jsonl", "embedding_model": model,
        "reports": len(cases), "incidents": len({c["incident"] for c in cases}),
        "pairs_compared": len(scored), "positive_pairs": len(positives),
        "configured_threshold": threshold, "min_semantic": min_sem,
        "at_configured_threshold": confusion(scored),
        "recall_same_language_pairs": _ratio(sum(r["predicted"] for r in positives if not r["cross_language"]),
                                             sum(1 for r in positives if not r["cross_language"])),
        "recall_cross_language_pairs": _ratio(sum(r["predicted"] for r in positives if r["cross_language"]),
                                              sum(1 for r in positives if r["cross_language"])),
        "threshold_sweep_diagnostic_only": sweep,
        "false_positives": [{k: r[k] for k in ("a", "b", "score", "semantic")} for r in scored if r["predicted"] and not r["same_incident"]],
        "false_negatives": [{k: r[k] for k in ("a", "b", "score", "semantic")} for r in positives if not r["predicted"]],
        "note": "Thresholds were set before this dataset existed; the sweep is diagnostic and was not used to tune them.",
    }


# -------------------------------------------------------------------------------------------- rag
def eval_rag(db, k: int = 5) -> dict:
    from sqlalchemy import select

    from app.agents import rag
    from app.agents.intake import run_intake
    from app.llm import embeddings
    from app.models import GrievanceCategory

    cats = {c.code: c for c in db.scalars(select(GrievanceCategory))}
    out = {}
    for mode in ("unfiltered", "production"):
        per_lang = defaultdict(lambda: {"p_at_k": [], "hit1": [], "rr": [], "cross": []})
        empty = 0
        for case in _jsonl("intake.jsonl"):
            vec = embeddings.embed_text(case["text"])
            if mode == "unfiltered":
                found = rag.retrieve(db, vec, category_id=None, department_id=None, k=k)
            else:
                pred = cats[run_intake(db, case["text"], use_llm=False).category_code]
                found = rag.retrieve(db, vec, category_id=pred.id, department_id=pred.department_id, k=k)
            if not found:
                empty += 1
            rel = [p.grievance.category_id == cats[case["category"]].id for p in found]
            first = next((i for i, r in enumerate(rel) if r), None)
            bucket = per_lang[case["lang"]]
            bucket["p_at_k"].append(sum(rel) / k)
            bucket["hit1"].append(1.0 if rel and rel[0] else 0.0)
            bucket["rr"].append(1.0 / (first + 1) if first is not None else 0.0)
            qlang = EXPECTED_LANG[case["lang"]]
            bucket["cross"].append(sum(p.grievance.language != qlang for p in found) / len(found) if found else 0.0)

        def agg(bs):
            vals = defaultdict(list)
            for b in bs:
                for key, v in b.items():
                    vals[key] += v
            n = len(vals["p_at_k"])
            return {"queries": n, f"precision_at_{k}": round(sum(vals["p_at_k"]) / n, 4), "hit_at_1": round(sum(vals["hit1"]) / n, 4),
                    "mrr": round(sum(vals["rr"]) / n, 4), "share_of_results_in_other_language": round(sum(vals["cross"]) / n, 4)}

        out[mode] = {"overall": agg(per_lang.values()), "by_language": {lang: agg([b]) for lang, b in sorted(per_lang.items())},
                     "queries_with_no_results": empty}
    return {"dataset": "queries: evals/datasets/intake.jsonl; corpus: synthetic grievance_history.csv (resolved cases)",
            "embedding_model": embeddings.provider_name(), "k": k,
            "relevance_definition": "a retrieved precedent is relevant when it has the query's gold category (proxy; no human relevance judgements)",
            "modes": {"unfiltered": "vector search over all resolved cases (measures the embedder)",
                      "production": "category -> department -> all widening, using the rules classifier's predicted category"},
            **out}


# -------------------------------------------------------------------------------------------- sla
def _parse(ts: str) -> datetime:
    return datetime.fromisoformat(ts)


def _auc(scores: list[float], labels: list[bool]) -> float | None:
    pos = [s for s, y in zip(scores, labels) if y]
    neg = [s for s, y in zip(scores, labels) if not y]
    if not pos or not neg:
        return None
    wins = sum(1.0 if p > n else 0.5 if p == n else 0.0 for p in pos for n in neg)
    return round(wins / (len(pos) * len(neg)), 4)


def _calibration(probs: list[float], labels: list[bool], bins: int = 10) -> dict:
    n = len(probs)
    table, ece = [], 0.0
    for b in range(bins):
        lo, hi = b / bins, (b + 1) / bins
        idx = [i for i, p in enumerate(probs) if (lo <= p < hi) or (b == bins - 1 and p == 1.0)]
        if not idx:
            continue
        conf = sum(probs[i] for i in idx) / len(idx)
        acc = sum(labels[i] for i in idx) / len(idx)
        ece += len(idx) / n * abs(conf - acc)
        table.append({"bin": f"[{lo:.1f},{hi:.1f})", "count": len(idx), "mean_predicted": round(conf, 3), "observed_rate": round(acc, 3)})
    brier = sum((p - y) ** 2 for p, y in zip(probs, labels)) / n
    eps = 1e-6
    logloss = -sum(math.log(max(eps, p if y else 1 - p)) for p, y in zip(probs, labels)) / n
    return {"ece_10_bins": round(ece, 4), "brier": round(brier, 4), "log_loss": round(logloss, 4), "auc": _auc(probs, labels),
            "reliability": table}


def eval_sla() -> dict:
    from app.agents.predictive import COLD_START_MIN_SAMPLES, estimate

    sla_by_cat, dept_by_cat = {}, {}
    with open(BACKEND / "data/synthetic/categories.csv", encoding="utf-8") as fh:
        for r in csv.DictReader(fh):
            sla_by_cat[r["category_code"]], dept_by_cat[r["category_code"]] = float(r["sla_hours"]), r["department_code"]
    with open(BACKEND / "data/synthetic/grievance_history.csv", encoding="utf-8") as fh:
        rows = [r for r in csv.DictReader(fh)]
    for r in rows:
        r["_c"], r["_r"] = _parse(r["created_at"]), _parse(r["resolved_at"])
        r["_h"] = (r["_r"] - r["_c"]).total_seconds() / 3600
        r["_sla"] = sla_by_cat[r["category_code"]]
    # The generator clamps resolutions that would fall after its "now" to now-1h (right-censoring).
    # Those rows have artificially short times and are excluded rather than silently biasing labels.
    latest = max(r["_r"] for r in rows)
    censored = [r for r in rows if r["_r"] == latest]
    usable = sorted((r for r in rows if r["_r"] != latest), key=lambda r: r["_c"])
    cut = int(len(usable) * 0.7)
    test = usable[cut:]
    test_start = test[0]["_c"]

    variants = {"production (category pool, urgency factor)": dict(urgency=True),
                "without urgency factor": dict(urgency=False)}
    results, leakage_violations = {}, 0
    preds_by_variant: dict[str, list[float]] = {v: [] for v in variants}
    base_rate, labels, mae = [], [], {v: [] for v in variants}
    for t in test:
        history = [r for r in usable if r["_r"] <= t["_c"]]  # only outcomes known when the complaint was filed
        leakage_violations += sum(1 for r in history if r["_r"] > t["_c"])
        pool = [r["_h"] for r in history if r["category_code"] == t["category_code"]]
        if len(pool) < COLD_START_MIN_SAMPLES:
            pool = [r["_h"] for r in history if dept_by_cat[r["category_code"]] == dept_by_cat[t["category_code"]]]
        label = t["_h"] > t["_sla"]
        labels.append(label)
        hist_breach = [r["_h"] > r["_sla"] for r in history]
        base_rate.append(sum(hist_breach) / len(hist_breach) if hist_breach else 0.3)
        for name, cfg in variants.items():
            predicted, prob = estimate(pool, t["_sla"], urgency=t["urgency"] if cfg["urgency"] else "medium")
            preds_by_variant[name].append(prob)
            mae[name].append(abs(predicted - t["_h"]))
    for name in variants:
        results[name] = {**_calibration(preds_by_variant[name], labels),
                         "resolution_time_mae_hours": round(sum(mae[name]) / len(mae[name]), 2),
                         "alert_at_0_6": _prf(*_alert(preds_by_variant[name], labels))}
    results["baseline: historical base rate"] = _calibration(base_rate, labels)
    results["baseline: constant 0.3 (cold-start default)"] = _calibration([0.3] * len(labels), labels)
    return {
        "dataset": "backend/data/synthetic/grievance_history.csv (SYNTHETIC, generated with seed 20261111)",
        "method": "chronological rolling-origin: first 70% of cases by creation time are history only; each of the last 30% "
                  "is predicted from cases resolved before it was filed",
        "rows_total": len(rows), "rows_excluded_right_censored": len(censored), "test_cases": len(test),
        "test_period_start": test_start.isoformat(), "breach_rate_in_test": _ratio(sum(labels), len(labels)),
        "leakage_violations": leakage_violations, "load_factor": "1.0 (historical department load is not recorded)",
        "variants": results,
        "caveat": "The synthetic generator draws resolution times from a per-category log-normal distribution that does not "
                  "depend on time, urgency or load. Good numbers here show the estimator recovers that distribution; they "
                  "are not evidence of real-world accuracy.",
    }


def _alert(probs: list[float], labels: list[bool], cut: float = 0.6) -> tuple[int, int, int, int]:
    tp = sum(1 for p, y in zip(probs, labels) if p >= cut and y)
    fp = sum(1 for p, y in zip(probs, labels) if p >= cut and not y)
    fn = sum(1 for p, y in zip(probs, labels) if p < cut and y)
    tn = sum(1 for p, y in zip(probs, labels) if p < cut and not y)
    return tp, fp, fn, tn


# ----------------------------------------------------------------------------------------- report
def _markdown(res: dict) -> str:
    i, j, d, r, s = res["intake"], res["injection"], res["duplicates"], res["rag"], res["sla"]
    fmt = lambda x: f"{x['value']:.3f} ({x['num']}/{x['den']})" if x["value"] is not None else "n/a"
    lines = [f"# Evaluation results: `{res['embedder']}` embedder", "",
             f"Generated {res['generated_at']} by `python -m evals.run --embedder {res['embedder']}` "
             f"(Python {res['python']}, seed {SEED}). LLM calls disabled. All inputs are author-written or SYNTHETIC; see evals/README.md.", "",
             "## Intake (rules classifier)", "",
             f"- Category accuracy: {fmt(i['accuracy'])}",
             *[f"  - `{k}`: {fmt(v)}" for k, v in i["accuracy_by_language"].items()],
             f"- Language detection: {fmt(i['language_detection_accuracy'])}",
             f"- Sensitive cases routed to human review: {fmt(i['sensitive_routed_to_human_review'])}",
             f"- Non-sensitive cases sent to review (workload cost): {fmt(i['non_sensitive_sent_to_review'])}",
             f"- Misclassified: {', '.join(e['id'] + ' ' + e['expected'] + '→' + e['predicted'] for e in i['errors']) or 'none'}", "",
             "## Prompt-injection guard", "",
             f"- Precision {j['precision']}, recall {j['recall']} (TP {j['tp']}, FP {j['fp']}, FN {j['fn']}, TN {j['tn']})",
             f"- Missed: {', '.join(j['missed']) or 'none'}; false alarms: {', '.join(j['false_alarms']) or 'none'}", "",
             f"## Duplicate detection (`{d['embedding_model']}`)", "",
             f"- {d['reports']} reports, {d['incidents']} incidents, {d['pairs_compared']} same-department pairs, {d['positive_pairs']} true duplicate pairs",
             f"- At configured threshold {d['configured_threshold']} (min semantic {d['min_semantic']}): "
             f"precision {d['at_configured_threshold']['precision']}, recall {d['at_configured_threshold']['recall']}, "
             f"F1 {d['at_configured_threshold']['f1']}, FPR {d['at_configured_threshold']['false_positive_rate']}, "
             f"FNR {d['at_configured_threshold']['false_negative_rate']}",
             f"- Recall, same-language pairs: {fmt(d['recall_same_language_pairs'])}; cross-language pairs: {fmt(d['recall_cross_language_pairs'])}", "",
             f"## Retrieval (`{r['embedding_model']}`, k={r['k']})", "",
             f"Relevance proxy: {r['relevance_definition']}.", "",
             "| Mode | P@5 | Hit@1 | MRR | Other-language share |", "| --- | --- | --- | --- | --- |",
             *[f"| {m} | {r[m]['overall']['precision_at_5']} | {r[m]['overall']['hit_at_1']} | {r[m]['overall']['mrr']} | "
               f"{r[m]['overall']['share_of_results_in_other_language']} |" for m in ("unfiltered", "production")], "",
             "Unfiltered, by query language:", "", "| Language | Queries | P@5 | MRR |", "| --- | --- | --- | --- |",
             *[f"| {k} | {v['queries']} | {v['precision_at_5']} | {v['mrr']} |" for k, v in r["unfiltered"]["by_language"].items()], "",
             "## SLA breach prediction (chronological backtest)", "",
             f"- {s['test_cases']} test cases from {s['test_period_start'][:10]}; breach rate {fmt(s['breach_rate_in_test'])}; "
             f"{s['rows_excluded_right_censored']} right-censored rows excluded; leakage violations: {s['leakage_violations']}", "",
             "| Predictor | ECE | Brier | AUC | Log loss |", "| --- | --- | --- | --- | --- |",
             *[f"| {k} | {v['ece_10_bins']} | {v['brier']} | {v['auc']} | {v['log_loss']} |" for k, v in s["variants"].items()], "",
             f"> {s['caveat']}", ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> dict:
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    p.add_argument("--embedder", choices=["hashing", "sentence-transformers"], default="hashing")
    args = p.parse_args(argv)
    _configure(args.embedder)

    sys.path.insert(0, str(BACKEND))
    import app.models  # noqa: F401
    from app.core.config import get_settings
    from app.db.session import Base, SessionLocal, configure_engine
    from app.llm import embeddings
    from app.services.seed import seed_datasets

    get_settings.cache_clear()
    engine = configure_engine(get_settings().database_url)
    Base.metadata.create_all(engine)
    with SessionLocal() as db:
        seed_datasets(db)
        if args.embedder == "sentence-transformers" and not embeddings.provider_name().startswith("sentence"):
            raise SystemExit("sentence-transformers is not available; install requirements-ml.txt or use --embedder hashing")
        res = {"embedder": args.embedder, "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
               "python": sys.version.split()[0], "seed": SEED,
               "intake": eval_intake(db), "injection": eval_injection(), "duplicates": eval_duplicates(db),
               "rag": eval_rag(db), "sla": eval_sla()}
    engine.dispose()
    RESULTS.mkdir(exist_ok=True)
    (RESULTS / f"{args.embedder}.json").write_text(json.dumps(res, ensure_ascii=False, indent=2), encoding="utf-8")
    (RESULTS / f"{args.embedder}.md").write_text(_markdown(res), encoding="utf-8")
    sys.stdout.buffer.write(_markdown(res).encode("utf-8") + b"\n")
    return res


if __name__ == "__main__":
    main()
